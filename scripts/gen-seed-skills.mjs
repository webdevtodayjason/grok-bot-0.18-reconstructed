// Bake the managed skills the host cannot fetch into the bundle.
//
// Managed skills normally arrive from Cursor's dashboard and land in the sand root's
// managed-skills cache. This box has no Cursor login, so that fetch always fails and
// `learn-from-demonstration` never exists -- which is exactly the skill teach-by-demonstration
// dispatches after a recording, so stop-with-save failed with "learning workflow is unavailable".
//
// The host ships as one host-main.cjs, so it cannot read these files off disk at runtime: they
// have to be inside the bundle. This turns each seed-skills/<id>/SKILL.md into a template
// literal in a generated module. The ManagedSkill fields are derived at load time through the
// same normalizer the Cursor fetch uses (fetchedManagedSkillToSandSkill), so a seed and a
// fetched copy of the same file are byte-identical -- the id comes from the directory name, and
// the name and description come from the file's own frontmatter.
//
//   node scripts/gen-seed-skills.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const seedDir = join(repoRoot, "source/host/extensions/managed-setup/seed-skills");
const outPath = join(repoRoot, "source/host/extensions/managed-setup/seed-skills.gen.ts");

// A template literal ends at a backtick and interpolates at `${`; nothing else in markdown needs
// escaping, and a backslash has to be doubled first or it would escape the escapes.
const asTemplateLiteral = (text) =>
  "`" + text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

const ids = readdirSync(seedDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
if (ids.length === 0) throw new Error(`no seed skills under ${seedDir}`);

const entries = ids.map((id) => {
  const raw = readFileSync(join(seedDir, id, "SKILL.md"), "utf8");
  if (!raw.startsWith("---\n")) throw new Error(`${id}/SKILL.md has no YAML frontmatter`);
  return `  { id: ${JSON.stringify(id)}, description: "", enabled: true, content: ${asTemplateLiteral(raw)} },`;
});

const banner = `// GENERATED by scripts/gen-seed-skills.mjs from seed-skills/<id>/SKILL.md. Do not edit by hand.
//
// These are the managed skills the host must have even with no Cursor login. The host is a single
// bundled file, so the markdown lives here verbatim rather than being read off disk at runtime.
// SandManagedSkillsService writes the union of these and whatever a fetch returned, with the
// fetched copy winning on an id collision, so a real Cursor refresh still replaces a seed.
`;

const body = `${banner}
import { fetchedManagedSkillToSandSkill, type FetchedManagedSkill } from "./sand-managed-skills.js";
import type { ManagedSkill } from "./managed-skills-cache.js";

const SEED_SKILL_FILES: readonly FetchedManagedSkill[] = [
${entries.join("\n")}
];

/** Normalized the same way a fetched skill is, so a seed and a fetched copy have one shape. */
export const SEED_MANAGED_SKILLS: ManagedSkill[] = SEED_SKILL_FILES
  .flatMap((skill) => { const normalized = fetchedManagedSkillToSandSkill(skill); return normalized == null ? [] : [normalized]; });
`;

writeFileSync(outPath, body, "utf8");
console.log(`wrote ${outPath} (${ids.length} skill(s): ${ids.join(", ")})`);
